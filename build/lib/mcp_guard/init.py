"""`mcp-guard init`: connect to an MCP server, read its tools and write a starter policy.

The generated policy is deliberately a starting point, not a finished one:
- one role (`agent`) granted every discovered tool, and one user (`my-agent`) holding that role;
- argument limits taken from each tool's own input schema (maxLength, minimum/maximum, enum), with a length cap on
  strings that have none;
- tools whose names suggest they send data out (email, notify, post, upload, webhook...) are marked `egress: external`
  with PII redaction and injection blocking on their arguments;
- tools whose names suggest destructive or code-running actions (delete, drop, exec, shell, run...) get a one-call
  budget and a REVIEW comment;
- injection removal and PII redaction on every tool's results;
- each tool's fingerprint pinned, so a later change to a tool's description or schema is caught (rug pull, ASI04).

Every choice is written as a commented line so the owner can see what to tighten.
"""
import re
from pathlib import Path

import yaml

from mcp_guard.policy import tool_fingerprint

EGRESS = re.compile(r"(send|email|mail|notify|message|post|publish|tweet|upload|webhook|http|fetch|slack|sms)", re.I)
DANGER = re.compile(r"(delete|drop|remove|destroy|truncate|exec|shell|command|run|eval|write|update|transfer|pay)", re.I)
DEFAULT_MAX_LENGTH = 10000


def arg_rules(schema: dict | None) -> dict:
    rules = {}
    for name, prop in ((schema or {}).get("properties") or {}).items():
        prop = prop or {}
        for alt in prop.get("anyOf") or prop.get("oneOf") or []:  # Optional[X] is written as anyOf [X, null]
            if alt.get("type") not in (None, "null"):
                prop = {**alt, **{k: v for k, v in prop.items() if k not in ("anyOf", "oneOf")}}
                break
        kind = prop.get("type")
        if isinstance(kind, list):  # "type": ["string", "null"]
            kind = next((k for k in kind if k != "null"), None)
        r = {}
        if "enum" in prop:
            r["enum"] = list(prop["enum"])
        elif kind == "string":
            r["max_length"] = int(prop.get("maxLength", DEFAULT_MAX_LENGTH))
        elif kind in ("integer", "number"):
            if "minimum" in prop:
                r["min"] = prop["minimum"]
            if "maximum" in prop:
                r["max"] = prop["maximum"]
        rules[name] = r
    return rules


def build_policy(tools: list[dict], role: str = "agent", user: str = "my-agent") -> str:
    """YAML text of a starter policy for the given tool listings (name, description, inputSchema)."""
    names = [t["name"] for t in tools]
    lines = [
        "# MCP Guard policy, generated by `mcp-guard init`. Review it before production use:",
        "# tighten roles, argument limits and budgets, then run `mcp-guard check` on it.",
        "# Default deny: a tool missing from `tools`, or not granted through `roles`, is hidden and blocked.",
        "",
        "detectors:",
        "  injection_threshold: 3        # lower = stricter prompt-injection detection",
        "",
        "session:",
        "  max_calls: 50                 # calls per agent session before it is ended (runaway loops, ASI08)",
        "  max_violations_before_terminate: 3",
        "",
        "roles:",
        f"  {role}: [{', '.join(names)}]",
        "  # readonly: [ ... ]           # split tools into narrower roles where you can (least privilege)",
        "",
        "users:                         # who an agent acts for -> roles. Over HTTP with a JWT, the token's sub",
        f"  {user}: [{role}]",
        "",
        "tools:",
    ]
    for t in tools:
        name = t["name"]
        rules = arg_rules(t.get("inputSchema"))
        egress, danger = bool(EGRESS.search(name)), bool(DANGER.search(name))
        lines.append(f"  {name}:")
        if danger:
            lines.append("    # REVIEW: the name suggests a destructive or code-running action. Grant it only to roles")
            lines.append("    # that need it, and consider the sandbox for the server.")
        if egress:
            lines.append("    egress: external             # sends data out of the company: PII in arguments is redacted")
        if rules:
            lines.append("    args:")
            for arg, r in rules.items():
                lines.append(f"      {arg}: {yaml.safe_dump(r, default_flow_style=True).strip()}")
        else:
            lines.append("    args: {}")
        if egress:
            lines.append("    redact_pii_in_args: true")
            lines.append("    on_injection_in_args: block")
        else:
            lines.append("    on_injection_in_args: alert   # block, alert or redact")
        lines.append("    on_injection_in_result: redact")
        lines.append("    redact_pii_in_result: true")
        lines.append(f"    max_calls_per_session: {1 if danger else 20}")
        lines.append("")
    lines.append("pins:                          # fingerprints of the tools as reviewed; a change hides the tool")
    for t in tools:
        lines.append(f"  {t['name']}: {tool_fingerprint(t['name'], t.get('description'), t.get('inputSchema'))}")
    lines += [
        "",
        "# Optional: run a local tool server in a locked-down container (see README, Sandbox).",
        "# sandbox:",
        "#   enabled: true",
        "#   image: my-tool-server:latest",
        "#   network: none",
        "#   env: []",
        "",
        "# Optional: environment variables an unsandboxed local server may see (default: all of them).",
        "# upstream_env: [DATABASE_URL]",
        "",
        "# Optional: hosts a remote (HTTP) server may be on.",
        "# upstream_allowed_hosts: [tools.example.com]",
        "",
    ]
    return "\n".join(lines)


def client_snippet(upstream: str, policy_path: Path, user: str) -> str:
    """How to point an MCP client at the gateway instead of the server (Claude Desktop / Cursor style JSON)."""
    import json
    cfg = {"mcpServers": {"guarded-tools": {
        "command": "mcp-guard", "args": ["proxy"],
        "env": {"MCP_GUARD_UPSTREAM": upstream, "MCP_GUARD_POLICY": str(policy_path.resolve()),
                "MCP_GUARD_USER": user, "MCP_GUARD_AUDIT_LOG": str(policy_path.resolve().parent / "audit.jsonl")}}}}
    return json.dumps(cfg, indent=2)


async def discover(upstream: str) -> list[dict]:
    """Tool listings of the server, connected the same way the gateway will connect to it."""
    from mcp import Client

    from mcp_guard.policy import Policy
    from mcp_guard.proxy import connect_upstream
    async with Client(connect_upstream(upstream, Policy(roles={}, users={}, tools={}))) as c:
        listed = await c.list_tools()
    return [t.model_dump(by_alias=True) for t in listed.tools]
